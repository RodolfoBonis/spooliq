func TestParseGCode_Cura(t *testing.T) {
	a := analyzeFixture(t, "cura.gcode")

	if a.Slicer.Name != "Cura" {
		t.Errorf("slicer name = %q", a.Slicer.Name)
	}
	if a.Slicer.Version != "5.6.0" {
		t.Errorf("slicer version = %q", a.Slicer.Version)
	}
	p := a.Plates[0]
	if p.PrintTimeSeconds != 3600 {
		t.Errorf("print time = %d", p.PrintTimeSeconds)
	}
	if !p.Estimated {
		t.Errorf("expected estimated=true for Cura (grams from length)")
	}
	if len(p.Filaments) != 1 {
		t.Fatalf("filaments = %d", len(p.Filaments))
	}
	// 3.21 m of 1.75mm PLA ~= 9.57 g.
	if g := p.Filaments[0].Grams; g < 9.4 || g > 9.7 {
		t.Errorf("estimated grams = %v, want ~9.57", g)
	}
	if p.Filaments[0].LengthMM == nil || *p.Filaments[0].LengthMM != 3210 {
		t.Errorf("length = %v", p.Filaments[0].LengthMM)
	}
}

// TestParseGCode_TailScan ensures metadata placed AFTER the 2MB head window (near
// the end of the file) is still found via the tail pass.
func TestParseGCode_TailScan(t *testing.T) {
	var buf bytes.Buffer
	buf.WriteString("; generated by PrusaSlicer 2.7.1 on test\n")
	// ~3MB of non-metadata moves to push the footer past the head window.
	line := "G1 X100 Y100 E1.5 F1200\n"
	for buf.Len() < 3<<20 {
		buf.WriteString(line)
	}
	buf.WriteString("; filament used [g] = 42.00\n")
	buf.WriteString("; estimated printing time (normal mode) = 3h 0m 0s\n")

	data := buf.Bytes()
	a, err := ParseGCode(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		t.Fatalf("ParseGCode: %v", err)
	}
	p := a.Plates[0]
	if p.PrintTimeSeconds != 3*3600 {
		t.Errorf("print time = %d, tail metadata not found", p.PrintTimeSeconds)
	}
	if len(p.Filaments) != 1 || p.Filaments[0].Grams != 42.0 {
		t.Errorf("filaments = %+v, tail metadata not found", p.Filaments)
	}
}
