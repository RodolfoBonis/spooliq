func analyzeFixture(t *testing.T, name string) *entities.Analysis {
	t.Helper()
	f, err := os.Open("testdata/" + name)
	if err != nil {
		t.Fatalf("open fixture: %v", err)
	}
	t.Cleanup(func() { _ = f.Close() })
	info, err := f.Stat()
	if err != nil {
		t.Fatalf("stat fixture: %v", err)
	}
	a, err := ParseGCode(f, info.Size())
	if err != nil {
		t.Fatalf("ParseGCode: %v", err)
	}
	return a
}

func TestParseGCode_PrusaSlicer(t *testing.T) {
	a := analyzeFixture(t, "prusaslicer.gcode")

	if a.Source != entities.SourceGCode {
		t.Errorf("source = %q", a.Source)
	}
	if a.Slicer.Name != "PrusaSlicer" {
		t.Errorf("slicer name = %q", a.Slicer.Name)
	}
	if !strings.HasPrefix(a.Slicer.Version, "2.7.1") {
		t.Errorf("slicer version = %q", a.Slicer.Version)
	}
	if len(a.Plates) != 1 {
		t.Fatalf("plates = %d", len(a.Plates))
	}
	p := a.Plates[0]
	if p.PrintTimeSeconds != 1*3600+23*60+45 {
		t.Errorf("print time = %d", p.PrintTimeSeconds)
	}
	if p.Estimated {
		t.Errorf("expected estimated=false")
	}
	if len(p.Filaments) != 2 {
		t.Fatalf("filaments = %d", len(p.Filaments))
	}
	if p.Filaments[0].Grams != 9.85 || p.Filaments[0].ColorHex != "#FF8800" || p.Filaments[0].Material != "PLA" {
		t.Errorf("slot1 = %+v", p.Filaments[0])
	}
	if p.Filaments[0].LengthMM == nil || *p.Filaments[0].LengthMM != 3300.5 {
		t.Errorf("slot1 length = %v", p.Filaments[0].LengthMM)
	}
	if p.Filaments[1].Grams != 3.58 || p.Filaments[1].ColorHex != "#1188FF" || p.Filaments[1].Material != "PETG" {
		t.Errorf("slot2 = %+v", p.Filaments[1])
	}
}

