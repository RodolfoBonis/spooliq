// noopCatalog yields no filaments, so suggestions resolve to nil.
type noopCatalog struct{}

func (noopCatalog) LoadCandidates(_ context.Context, _ string) ([]suggest.Candidate, error) {
	return nil, nil
}

func newUC() *SlicerUseCase {
	svc := service.NewService(noopCatalog{}, &logger.NoopLogger{})
	return &SlicerUseCase{service: svc, logger: &logger.NoopLogger{}}
}

func ctxWithOrg(org string) (*gin.Context, *httptest.ResponseRecorder) {
	rec := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(rec)
	if org != "" {
		c.Set("organization_id", org)
	}
	c.Set("user_id", "user-1")
	return c, rec
}

func multipartReqBytes(t *testing.T, filename string, content []byte) *http.Request {
	t.Helper()
	var buf bytes.Buffer
	w := multipart.NewWriter(&buf)
	if filename != "" {
		fw, err := w.CreateFormFile("file", filename)
		require.NoError(t, err)
		_, _ = fw.Write(content)
	}
	_ = w.Close()
	req := httptest.NewRequest(http.MethodPost, "/slicer/analyze", &buf)
	req.Header.Set("Content-Type", w.FormDataContentType())
	return req
}

func multipartReq(t *testing.T, filename, content string) *http.Request {
	return multipartReqBytes(t, filename, []byte(content))
}

func decode(t *testing.T, rec *httptest.ResponseRecorder) map[string]any {
	t.Helper()
	var body map[string]any
	require.NoError(t, json.Unmarshal(rec.Body.Bytes(), &body))
	return body
}

func zipBytes(t *testing.T, entries map[string]string) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for name, content := range entries {
		w, err := zw.Create(name)
		require.NoError(t, err)
		_, err = w.Write([]byte(content))
		require.NoError(t, err)
	}
	require.NoError(t, zw.Close())
	return buf.Bytes()
}

const prusaGCode = "; generated by PrusaSlicer 2.7.1 on test\n" +
	"; estimated printing time (normal mode) = 1h 0m 0s\n" +
	"; filament used [g] = 10.00, 5.00\n" +
	"; filament_colour = #FF0000;#00FF00\n" +
	"; filament_type = PLA;PETG\n"

func TestAnalyze_OrganizationRequired(t *testing.T) {
	uc := newUC()
	c, rec := ctxWithOrg("")
	c.Request = multipartReq(t, "a.gcode", prusaGCode)
	uc.Analyze(c)
	assert.Equal(t, http.StatusBadRequest, rec.Code)
	assert.Equal(t, "organization_required", decode(t, rec)["code"])
}

