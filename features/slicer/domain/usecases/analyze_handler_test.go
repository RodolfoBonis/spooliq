func TestAnalyze_Success(t *testing.T) {
	uc := newUC()
	c, rec := ctxWithOrg("org-1")
	c.Request = multipartReq(t, "part.gcode", prusaGCode)
	uc.Analyze(c)
	require.Equal(t, http.StatusOK, rec.Code)

	body := decode(t, rec)
	assert.Equal(t, "gcode", body["source"])
	plates, ok := body["plates"].([]any)
	require.True(t, ok)
	require.Len(t, plates, 1)
	plate := plates[0].(map[string]any)
	assert.EqualValues(t, 3600, plate["print_time_seconds"])
	fils := plate["filaments"].([]any)
	require.Len(t, fils, 2)
	// With an empty catalog, suggestion must be present and null.
	f0 := fils[0].(map[string]any)
	assert.Contains(t, f0, "suggestion")
	assert.Nil(t, f0["suggestion"])
}

